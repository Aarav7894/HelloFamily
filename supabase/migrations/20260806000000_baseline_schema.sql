-- Shared helper functions
-- ============================================================

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- private schema: SECURITY DEFINER helpers used inside RLS policies, so a
-- policy checking "is this user connected to that one" doesn't need the
-- querying role to have direct SELECT on family_connections itself.
create schema if not exists private;

create or replace function private.are_connected(first_user uuid, second_user uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.family_connections fc
    where fc.status = 'active'
      and (
        (fc.adult_child_id = first_user and fc.older_adult_id = second_user)
        or
        (fc.adult_child_id = second_user and fc.older_adult_id = first_user)
      )
  );
$$;

create or replace function private.is_connected_adult_child(possible_adult_child uuid, older_adult uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.family_connections fc
    where fc.status = 'active'
      and fc.adult_child_id = possible_adult_child
      and fc.older_adult_id = older_adult
  );
$$;

-- handle_new_user is defined here (it's a public-schema function); the
-- trigger that attaches it to auth.users lives in the separate
-- auth-schema migration file.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_role public.user_role;
  selected_timezone text;
begin
  selected_role :=
    case
      when new.raw_user_meta_data ->> 'role'
        in ('adult_child', 'older_adult')
      then (new.raw_user_meta_data ->> 'role')::public.user_role
      else null
    end;

  selected_timezone :=
    coalesce(
      nullif(new.raw_user_meta_data ->> 'timezone', ''),
      'America/Chicago'
    );

  insert into public.profiles (id, full_name, role, timezone)
  values (
    new.id,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    selected_role,
    selected_timezone
  );

  insert into public.notification_preferences (user_id, timezone)
  values (new.id, selected_timezone);

  return new;
end;
$$;

-- ============================================================
-- profiles
-- ============================================================

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  role public.user_role,
  timezone text not null default 'America/Chicago',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_full_name_length check (
    full_name is null or (char_length(full_name) >= 1 and char_length(full_name) <= 100)
  )
);

alter table public.profiles enable row level security;

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

grant select, insert, update on public.profiles to authenticated;

create policy "Users can read their own or connected profiles"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id or private.are_connected((select auth.uid()), id));

create policy "Users can insert their own profile"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- ============================================================
-- family_connections
-- ============================================================

create table public.family_connections (
  id uuid primary key default gen_random_uuid(),
  adult_child_id uuid not null references public.profiles (id) on delete cascade,
  older_adult_id uuid not null references public.profiles (id) on delete cascade,
  status public.connection_status not null default 'active',
  connected_at timestamptz not null default now(),
  revoked_at timestamptz,
  constraint different_family_members check (adult_child_id <> older_adult_id),
  constraint unique_family_connection unique (adult_child_id, older_adult_id)
);

create index family_connections_adult_child_idx on public.family_connections (adult_child_id);
create index family_connections_older_adult_idx on public.family_connections (older_adult_id);

alter table public.family_connections enable row level security;

grant select on public.family_connections to authenticated;

create policy "Connected users can read their connection"
  on public.family_connections for select
  to authenticated
  using ((select auth.uid()) = adult_child_id or (select auth.uid()) = older_adult_id);

-- No insert/update/delete policy or grant for `authenticated`: connections
-- are only ever created via the redeem_invite() SECURITY DEFINER function
-- (see 20260812050147_create_invite_functions.sql).

