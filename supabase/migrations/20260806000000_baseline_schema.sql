-- ============================================================
-- check_ins
-- ============================================================

create table public.check_ins (
  id uuid primary key default gen_random_uuid(),
  older_adult_id uuid not null references public.profiles (id) on delete cascade,
  check_in_date date not null,
  feeling public.feeling_answer not null,
  physically_okay public.wellness_answer not null,
  normal_activities public.wellness_answer not null,
  concern_detected boolean generated always as (
    feeling = 'not_good'::public.feeling_answer
    or physically_okay = 'no'::public.wellness_answer
    or normal_activities = 'no'::public.wellness_answer
  ) stored,
  submitted_at timestamptz not null default now(),
  constraint one_check_in_per_day unique (older_adult_id, check_in_date)
);

create index check_ins_older_adult_date_idx on public.check_ins (older_adult_id, check_in_date desc);

alter table public.check_ins enable row level security;

grant select, insert on public.check_ins to authenticated;

create policy "Older adults can read their own answers"
  on public.check_ins for select
  to authenticated
  using ((select auth.uid()) = older_adult_id);

create policy "Older adults can submit their own check-ins"
  on public.check_ins for insert
  to authenticated
  with check ((select auth.uid()) = older_adult_id);

-- No update/delete policy or grant: check-in history is immutable from
-- the client by design.

-- ============================================================
-- daily_statuses
-- ============================================================

create table public.daily_statuses (
  id uuid primary key default gen_random_uuid(),
  older_adult_id uuid not null references public.profiles (id) on delete cascade,
  status_date date not null,
  status public.checkin_status not null,
  completed_at timestamptz,
  check_in_id uuid unique references public.check_ins (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint one_status_per_day unique (older_adult_id, status_date),
  constraint valid_status_details check (
    (status in ('completed', 'concern') and check_in_id is not null and completed_at is not null)
    or
    (status = 'missed' and check_in_id is null and completed_at is null)
  )
);

create index daily_statuses_older_adult_date_idx on public.daily_statuses (older_adult_id, status_date desc);

alter table public.daily_statuses enable row level security;

grant select on public.daily_statuses to authenticated;

create policy "Older adults and connected adult children can read statuses"
  on public.daily_statuses for select
  to authenticated
  using (
    (select auth.uid()) = older_adult_id
    or private.is_connected_adult_child((select auth.uid()), older_adult_id)
  );

-- No insert/update/delete policy or grant: rows are created only by the
-- create_status_from_check_in() trigger (or, in future, a trusted
-- scheduled backend process for "missed").

-- ============================================================
-- check_ins -> daily_statuses trigger
-- ============================================================

create or replace function public.create_status_from_check_in()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.daily_statuses (
    older_adult_id, status_date, status, completed_at, check_in_id
  )
  values (
    new.older_adult_id,
    new.check_in_date,
    case
      when new.concern_detected then 'concern'::public.checkin_status
      else 'completed'::public.checkin_status
    end,
    new.submitted_at,
    new.id
  );
  return new;
end;
$$;

create trigger on_check_in_created
  after insert on public.check_ins
  for each row execute function public.create_status_from_check_in();

